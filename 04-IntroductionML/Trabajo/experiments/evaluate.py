"""
Evaluation for trained Q-learning agent.

This script:
- Loads one or more trained Q-tables (policies)
- Evaluates each policy on both toy and plant graphs
- Tests across multiple queue levels (greedy policy, ε=0)
- Computes metrics: avg reward, avg steps, success rate
- Saves evaluation results to JSON and CSV tables
- NO PLOTS (plots are generated by plot_results.py)
"""

import sys
sys.path.insert(0, '../')

import numpy as np
from pathlib import Path
from typing import Dict, Any, List

from src.environment import RoutingEnv
from src.agent import QLearningAgent
from src.utils import (
    compute_eval_metrics,
    save_metrics_table_csv,
    save_json,
)
from config.graphs import (
    GRAPH_TOY,
    GRAPH_PLANT,
    NODE_ROLES_TOY,
    NODE_ROLES_PLANT,
    REWARD_PARAMS_DEFAULT,
    MAX_STEPS_TOY,
    MAX_STEPS,
    DEFAULT_START_CANDIDATES_TOY,
    DEFAULT_PICKUP_CANDIDATES_TOY,
    DEFAULT_DROP_CANDIDATES_TOY,
    DEFAULT_START_CANDIDATES,
    DEFAULT_PICKUP_CANDIDATES,
    DEFAULT_DROP_CANDIDATES,
)


# =================================================
#           EVALUATION CONFIGURATION
# =================================================

NUM_EVAL_EPISODES_PER_QUEUE = 50
QUEUE_LEVELS_TO_TEST = [0, 1, 2]
EVAL_SEED = 999

RESULTS_DIR = Path("../results")
MODELS_DIR = RESULTS_DIR / "models"
EVAL_DIR = RESULTS_DIR / "evaluation"

EVAL_DIR.mkdir(parents=True, exist_ok=True)


# ================================================
#              EVALUATION FUNCTIONS
# ================================================

def make_env(graph_name: str, queue_level: int, seed: int) -> RoutingEnv:
    """Create environment for a given graph and queue level."""
    if graph_name == "toy":
        env = RoutingEnv(
            graph=GRAPH_TOY,
            node_roles=NODE_ROLES_TOY,
            reward_params=REWARD_PARAMS_DEFAULT,
            max_steps=MAX_STEPS_TOY,
            start_candidates=DEFAULT_START_CANDIDATES_TOY,
            pickup_candidates=DEFAULT_PICKUP_CANDIDATES_TOY,
            drop_candidates=DEFAULT_DROP_CANDIDATES_TOY,
            queue_sampling="fixed",
            fixed_queue_level=queue_level,
            seed=seed,
        )
    elif graph_name == "plant":
        env = RoutingEnv(
            graph=GRAPH_PLANT,
            node_roles=NODE_ROLES_PLANT,
            reward_params=REWARD_PARAMS_DEFAULT,
            max_steps=MAX_STEPS,
            start_candidates=DEFAULT_START_CANDIDATES,
            pickup_candidates=DEFAULT_PICKUP_CANDIDATES,
            drop_candidates=DEFAULT_DROP_CANDIDATES,
            queue_sampling="fixed",
            fixed_queue_level=queue_level,
            penalize_revisits=True,
            revisit_penalty_factor=-2.0,
            seed=seed,
        )
    else:
        raise ValueError(f"Unknown graph_name: {graph_name}")
    
    return env


def evaluate_policy_on_graph(
    q_table_path: Path,
    policy_name: str,
    graph_name: str,
    queue_levels: List[int] = QUEUE_LEVELS_TO_TEST,
    episodes_per_queue: int = NUM_EVAL_EPISODES_PER_QUEUE,
    seed: int = EVAL_SEED,
) -> Dict[str, Any]:
    """Evaluate one policy on one graph across multiple queue levels."""
    rng = np.random.default_rng(seed)
    
    agent = QLearningAgent(alpha=0.0, gamma=0.0, epsilon=0.0)
    agent.load(str(q_table_path))
    agent.epsilon = 0.0
    
    all_episode_records: List[Dict[str, Any]] = []
    
    for q_level in queue_levels:
        env = make_env(graph_name, queue_level=q_level, seed=int(rng.integers(1e9)))
        
        for _ in range(episodes_per_queue):
            state = env.reset()
            done = False
            total_reward = 0.0
            steps = 0
            success_flag = False
            
            while not done:
                valid_actions = env.get_valid_actions()
                action = agent.select_action(state, valid_actions)
                
                next_state, reward, done, info = env.step(action)
                
                state = next_state
                total_reward += reward
                steps += 1
            
            termination_reason = info.get("termination_reason", "unknown")
            if termination_reason == "success":
                success_flag = True
            
            all_episode_records.append({
                "queue_level": q_level,
                "total_reward": total_reward,
                "steps": steps,
                "success": int(success_flag),
                "termination_reason": termination_reason,
            })
    
    metrics = compute_eval_metrics(all_episode_records)
    metrics["graph"] = graph_name
    metrics["policy_name"] = policy_name
    
    return metrics


def find_policies_to_evaluate() -> Dict[str, Path]:
    """Find all trained Q-tables to evaluate."""
    policies = {}
    
    toy_models = sorted(MODELS_DIR.glob("q_table_toy_final_*.pkl"))
    plant_models = sorted(MODELS_DIR.glob("q_table_plant_final_*.pkl"))
    
    if toy_models:
        policies["toy_final"] = toy_models[-1]
    
    if plant_models:
        policies["plant_final"] = plant_models[-1]
    
    return policies


# =============================================
#                   MAIN
# =============================================

def main():
    """Main evaluation function."""
    
    print("=" * 80)
    print("Q-LEARNING AGENT - COMPREHENSIVE EVALUATION")
    print("=" * 80)
    print()
    
    policies = find_policies_to_evaluate()
    
    if not policies:
        print("ERROR: No trained models found in", MODELS_DIR)
        print("Please run train.py first (for both toy and plant graphs)")
        return
    
    print(f"Found {len(policies)} policy/policies to evaluate:")
    for name, path in policies.items():
        print(f"  - {name}: {path.name}")
    print()
    
    print(f"Evaluation configuration:")
    print(f"  Episodes per queue level: {NUM_EVAL_EPISODES_PER_QUEUE}")
    print(f"  Queue levels to test: {QUEUE_LEVELS_TO_TEST}")
    print(f"  Policy: Greedy (ε=0)")
    print(f"  Random seed: {EVAL_SEED}")
    print("=" * 80)
    print()
    
    policies_metrics_toy: Dict[str, Dict[str, Any]] = {}
    policies_metrics_plant: Dict[str, Dict[str, Any]] = {}
    
    for policy_name, q_table_path in policies.items():
        print(f"\n{'=' * 80}")
        print(f"Evaluating policy: {policy_name}")
        print(f"Q-table: {q_table_path.name}")
        print(f"{'=' * 80}")
        
        # Evaluate on TOY graph
        print(f"\n  → Evaluating on TOY graph...")
        toy_metrics = evaluate_policy_on_graph(
            q_table_path=q_table_path,
            policy_name=policy_name,
            graph_name="toy",
        )
        policies_metrics_toy[policy_name] = toy_metrics
        
        print(f"     Overall: Reward={toy_metrics['avg_reward']:.2f}±{toy_metrics['std_reward']:.2f}, "
              f"Steps={toy_metrics['avg_steps']:.1f}±{toy_metrics['std_steps']:.1f}, "
              f"Success={toy_metrics['success_rate']:.1%}")
        
        toy_json_path = EVAL_DIR / f"evaluation_results_{policy_name}_toy.json"
        save_json(toy_metrics["per_queue"], toy_json_path)
        
        # Evaluate on PLANT graph
        print(f"\n  → Evaluating on PLANT graph...")
        plant_metrics = evaluate_policy_on_graph(
            q_table_path=q_table_path,
            policy_name=policy_name,
            graph_name="plant",
        )
        policies_metrics_plant[policy_name] = plant_metrics
        
        print(f"     Overall: Reward={plant_metrics['avg_reward']:.2f}±{plant_metrics['std_reward']:.2f}, "
              f"Steps={plant_metrics['avg_steps']:.1f}±{plant_metrics['std_steps']:.1f}, "
              f"Success={plant_metrics['success_rate']:.1%}")
        
        plant_json_path = EVAL_DIR / f"evaluation_results_{policy_name}_plant.json"
        save_json(plant_metrics["per_queue"], plant_json_path)
    
    # Save comparison tables
    print(f"\n{'=' * 80}")
    print("Saving comparison tables...")
    print(f"{'=' * 80}")
    
    toy_table_path = EVAL_DIR / "metrics_table_toy.csv"
    save_metrics_table_csv(policies_metrics_toy, toy_table_path)
    
    plant_table_path = EVAL_DIR / "metrics_table_plant.csv"
    save_metrics_table_csv(policies_metrics_plant, plant_table_path)
    
    print(f"\n{'=' * 80}")
    print("EVALUATION COMPLETE")
    print(f"{'=' * 80}")
    print("\nResults saved to:")
    print(f"  Toy metrics table:   {toy_table_path}")
    print(f"  Plant metrics table: {plant_table_path}")
    print(f"  Detailed JSONs:      {EVAL_DIR}")
    print("\nRun plot_results.py to generate all plots.")
    print("=" * 80)


if __name__ == "__main__":
    main()